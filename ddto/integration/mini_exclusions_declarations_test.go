package integration

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// A declaring receiver in the tested package and its promoted wrappers keep one
// policy. Explicit overrides and unrelated declarations with the same name do
// not. Only the tested package's own files are read: an annotation in an
// imported helper package has no effect.
func checkMiniPromotedExclusions(t *testing.T) {
	dir, driver := prepareMiniFixture(t)
	helper := installExternalTestifyHelper(t, dir)
	const record = `func record(t *testing.T){
 path:=filepath.Join(os.Getenv("DECLARATION_COUNTER"),strings.ReplaceAll(t.Name(),"/","_"))
 f,err:=os.OpenFile(path,os.O_CREATE|os.O_APPEND|os.O_WRONLY,0600);if err!=nil{t.Fatal(err)}
 _,err=f.WriteString("x");f.Close();if err!=nil{t.Fatal(err)}
}
`
	writeBuildFixture(t, helper, map[string]string{"hidden.go": `package testkit
import("os";"path/filepath";"strings";"testing";"github.com/stretchr/testify/suite")
` + record + `type hiddenSuite struct{suite.Suite}
//ddtest:no_auto_retry
func(s *hiddenSuite) TestHidden(){record(s.T());s.T().Error("imported annotation")}
func NewHidden() suite.TestingSuite{return new(hiddenSuite)}
`})
	writeBuildFixture(t, dir, map[string]string{"base.go": `package fixture
import("os";"path/filepath";"strings";"testing";"github.com/stretchr/testify/suite")
type Base struct{suite.Suite}
` + record + `//ddtest:prevent_failure_suppression
//ddtest:no_auto_retry
func(s (Alias)) TestCritical(){record(s.T());s.T().Error("protected declaration")}
//ddtest:no_auto_retry
func(s (Base)) TestValue(){record(s.T())}
`, "aliases.go": `package fixture
type Alias = Intermediate
type Intermediate = *Base
`, "declarations_test.go": `package fixture_test
import("os";"path/filepath";"strings";"testing";"example.com/dd-ci-testing-fixture";"example.com/external-testkit";"github.com/stretchr/testify/suite")
type Derived struct{fixture.Base}
type Override struct{fixture.Base}
type Ordinary struct{suite.Suite}
type LocalPointer struct{suite.Suite}
type LocalAlias = LocalPointerAlias
type LocalPointerAlias = *LocalPointer
//ddtest:no_auto_retry
func(s (LocalAlias)) TestLocalPointer(){recordDeclaration(s.T());s.T().Error("local pointer alias")}

func recordDeclaration(t *testing.T){
 path:=filepath.Join(os.Getenv("DECLARATION_COUNTER"),strings.ReplaceAll(t.Name(),"/","_"))
 f,err:=os.OpenFile(path,os.O_CREATE|os.O_APPEND|os.O_WRONLY,0600);if err!=nil{t.Fatal(err)}
 _,err=f.WriteString("x");f.Close();if err!=nil{t.Fatal(err)}
}
func(s *Override) TestCritical(){recordDeclaration(s.T());s.T().Error("ordinary override")}
func(s *Ordinary) TestCritical(){recordDeclaration(s.T());s.T().Error("ordinary independent declaration")}
func(s *Ordinary) TestValue(){recordDeclaration(s.T())}
func TestLocalPointer(t *testing.T){suite.Run(t,new(LocalPointer))}
func TestDerived(t *testing.T){suite.Run(t,new(Derived))}
func TestOverride(t *testing.T){suite.Run(t,new(Override))}
func TestOrdinaryDeclaration(t *testing.T){suite.Run(t,new(Ordinary))}
func TestHiddenDeclaration(t *testing.T){suite.Run(t,testkit.NewHidden())}
`})
	bin := filepath.Join(t.TempDir(), executableName("declarations.test"))
	out, stderr, code := command(t, dir, testEnv("DD_CIVISIBILITY_ENABLED=false"), driver, exclusionBuildArgs(bin, true)...)
	if code != 0 {
		t.Fatalf("compile %d: %s %s", code, out, stderr)
	}
	// Declaration registrations are compiled into the binary: the declaring
	// source may be absent when the tests run.
	if err := os.Rename(filepath.Join(dir, "base.go"), filepath.Join(dir, "base.go.saved")); err != nil {
		t.Fatal(err)
	}
	for _, mode := range []string{"in_process", "process"} {
		t.Run(mode, func(t *testing.T) {
			counters := t.TempDir()
			receiver, got := runParityCase(t, dir, bin, parityCase{Args: []string{"-test.run=^Test(Derived|Override|OrdinaryDeclaration|HiddenDeclaration|LocalPointer)$"}, Policy: policySettings{Retry: true, Quarantined: true, ManagementTarget: "TestDerived/TestCritical", ManagementSuite: "<autogenerated>/Derived"}, Env: []string{"DECLARATION_COUNTER=" + counters, "DD_CIVISIBILITY_FLAKY_RETRY_ENABLED=true", "DD_CIVISIBILITY_FLAKY_RETRY_COUNT=2", "DD_CIVISIBILITY_RETRY_EXECUTION_MODE=" + mode}})
			if got.code != 1 {
				t.Fatalf("exit %d: %s %s", got.code, got.out, got.stderr)
			}
			counts := map[string]string{
				"TestDerived/TestCritical": "x", "TestDerived/TestValue": "x",
				"TestHiddenDeclaration/TestHidden":  "xxx",
				"TestLocalPointer/TestLocalPointer": "x",
				"TestOverride/TestCritical":         "xxx", "TestOverride/TestValue": "x",
				"TestOrdinaryDeclaration/TestCritical": "xxx", "TestOrdinaryDeclaration/TestValue": "xxx",
			}
			for name, want := range counts {
				data, err := os.ReadFile(filepath.Join(counters, strings.ReplaceAll(name, "/", "_")))
				if err != nil || string(data) != want {
					t.Fatalf("%s calls=%q want=%q err=%v", name, data, want, err)
				}
			}
			protected, value, local := 0, 0, 0
			for _, event := range receiver.events {
				if event["type"] != "test" {
					continue
				}
				meta := event["content"].(map[string]any)["meta"].(map[string]any)
				name, _ := meta["test.name"].(string)
				if name == "TestDerived/TestCritical" {
					protected++
					for _, key := range []string{"prevent_failure_suppression", "no_auto_retry", "is_quarantined"} {
						if meta["test.test_management."+key] != "true" {
							t.Fatalf("promoted declaration lost %s: %v", key, meta)
						}
					}
				} else if name == "TestLocalPointer/TestLocalPointer" {
					local++
					if meta["test.test_management.no_auto_retry"] != "true" {
						t.Fatalf("pointer alias receiver lost declaration: %v", meta)
					}
				} else if name == "TestDerived/TestValue" || name == "TestOverride/TestValue" {
					value++
					if meta["test.test_management.no_auto_retry"] != "true" {
						t.Fatalf("value receiver declaration lost: %v", meta)
					}
					if meta["test.test_management.prevent_failure_suppression"] != nil {
						t.Fatalf("independent method inherited sibling annotation: %v", meta)
					}
				} else if strings.HasPrefix(name, "TestOverride/") || strings.HasPrefix(name, "TestOrdinaryDeclaration/") || strings.HasPrefix(name, "TestHiddenDeclaration/") {
					for _, key := range []string{"prevent_failure_suppression", "no_auto_retry"} {
						if meta["test.test_management."+key] != nil {
							t.Fatalf("override, unrelated or imported declaration leaked %s: %v", key, meta)
						}
					}
				}
			}
			if protected != 1 || value != 2 || local != 1 {
				t.Fatalf("protected events=%d value events=%d local alias events=%d", protected, value, local)
			}
		})
	}
}

// Cgo's compiler-selected Go sources participate in the same declaration scan
// as ordinary files.
func checkMiniCgoExclusions(t *testing.T) {
	dir, driver := prepareMiniFixture(t)
	out, stderr, code := command(t, dir, testEnv(), "go", "env", "CGO_ENABLED")
	if code != 0 {
		t.Fatalf("native cgo configuration: %s %s", out, stderr)
	}
	if strings.TrimSpace(out) != "1" {
		t.Skip("native toolchain disables cgo")
	}
	installExternalTestifyHelper(t, dir)
	writeBuildFixture(t, dir, map[string]string{"cgo.go": `package fixture
import "C"
import("os";"path/filepath";"strings";"github.com/stretchr/testify/suite")
type LocalCgo struct{suite.Suite}
type LocalAlias = LocalCgo
//ddtest:no_auto_retry
func(s *LocalAlias) TestCgo(){
 path:=filepath.Join(os.Getenv("DECLARATION_COUNTER"),strings.ReplaceAll(s.T().Name(),"/","_"))
 f,err:=os.OpenFile(path,os.O_CREATE|os.O_APPEND|os.O_WRONLY,0600);if err!=nil{s.T().Fatal(err)}
 _,err=f.WriteString("x");f.Close();if err!=nil{s.T().Fatal(err)}
 s.T().Error("local cgo annotation")
}
`, "cgo_test.go": `package fixture
import("testing";"github.com/stretchr/testify/suite")
func TestLocalCgo(t *testing.T){suite.Run(t,new(LocalCgo))}
`})
	bin := filepath.Join(t.TempDir(), executableName("cgo-declarations.test"))
	out, stderr, code = command(t, dir, testEnv("DD_CIVISIBILITY_ENABLED=false"), driver, exclusionBuildArgs(bin, true)...)
	if code != 0 {
		t.Fatalf("compile native cgo fixture %d: %s %s", code, out, stderr)
	}
	for _, mode := range []string{"in_process", "process"} {
		t.Run(mode, func(t *testing.T) {
			counters := t.TempDir()
			receiver, got := runParityCase(t, dir, bin, parityCase{Args: []string{"-test.run=^TestLocalCgo$"}, Policy: policySettings{Retry: true}, Env: []string{"DECLARATION_COUNTER=" + counters, "DD_CIVISIBILITY_FLAKY_RETRY_ENABLED=true", "DD_CIVISIBILITY_FLAKY_RETRY_COUNT=2", "DD_CIVISIBILITY_RETRY_EXECUTION_MODE=" + mode}})
			if got.code != 1 {
				t.Fatalf("exit %d: %s %s", got.code, got.out, got.stderr)
			}
			for _, name := range []string{"TestLocalCgo/TestCgo"} {
				data, err := os.ReadFile(filepath.Join(counters, strings.ReplaceAll(name, "/", "_")))
				if err != nil || string(data) != "x" {
					t.Fatalf("%s calls=%q want=x err=%v", name, data, err)
				}
				count := 0
				for _, event := range receiver.events {
					if event["type"] != "test" {
						continue
					}
					meta := event["content"].(map[string]any)["meta"].(map[string]any)
					if meta["test.name"] != name {
						continue
					}
					count++
					if meta["test.test_management.no_auto_retry"] != "true" || meta["test.is_retry"] != nil || meta["test.retry_reason"] != nil {
						t.Fatalf("cgo declaration tags: %v", meta)
					}
				}
				if count != 1 {
					t.Fatalf("%s emitted %d events, want one", name, count)
				}
			}
		})
	}
}
