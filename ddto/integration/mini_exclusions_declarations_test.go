// An imported declaring receiver and its promoted wrappers keep one policy.
// Explicit overrides and unrelated declarations with the same name do not.
func checkMiniImportedPromotedExclusions(t *testing.T) {
	dir, driver := prepareMiniFixture(t)
	helper := installExternalTestifyHelper(t, dir)
	// Dots in the last path component are escaped in compiler runtime names.
	for _, modDir := range []string{dir, helper} {
		modPath := filepath.Join(modDir, "go.mod")
		data, err := os.ReadFile(modPath)
		if err != nil {
			t.Fatal(err)
		}
		data = []byte(strings.ReplaceAll(string(data), "example.com/external-testkit", "example.com/external-testkit.v1"))
		if err := os.WriteFile(modPath, data, 0600); err != nil {
			t.Fatal(err)
		}
	}
	writeBuildFixture(t, helper, map[string]string{"base.go": `package testkit
import("os";"path/filepath";"strings";"testing";"github.com/stretchr/testify/suite")
type Base struct{suite.Suite}
func record(t *testing.T){
 path:=filepath.Join(os.Getenv("DECLARATION_COUNTER"),strings.ReplaceAll(t.Name(),"/","_"))
 f,err:=os.OpenFile(path,os.O_CREATE|os.O_APPEND|os.O_WRONLY,0600);if err!=nil{t.Fatal(err)}
 _,err=f.WriteString("x");f.Close();if err!=nil{t.Fatal(err)}
}
//ddtest:prevent_failure_suppression
//ddtest:no_auto_retry
func(s (Alias)) TestCritical(){record(s.T());s.T().Error("protected imported declaration")}
//ddtest:no_auto_retry
func(s (Base)) TestValue(){record(s.T())}
type hiddenSuite struct{suite.Suite}
//ddtest:no_auto_retry
func(s *hiddenSuite) TestHidden(){record(s.T());s.T().Error("private imported receiver")}
func NewHidden() suite.TestingSuite{return new(hiddenSuite)}
`, "aliases.go": `package testkit
type Alias = Intermediate
type Intermediate = *Base
`})
	writeBuildFixture(t, dir, map[string]string{"declarations_test.go": `package fixture_test
import("os";"path/filepath";"strings";"testing";"example.com/external-testkit.v1";"github.com/stretchr/testify/suite")
type Derived struct{testkit.Base}
type Override struct{testkit.Base}
type Ordinary struct{suite.Suite}
type LocalPointer struct{suite.Suite}
type LocalAlias = LocalPointerAlias
type LocalPointerAlias = *LocalPointer
//ddtest:no_auto_retry
func(s (LocalAlias)) TestLocalPointer(){recordDeclaration(s.T());s.T().Error("local pointer alias")}

func recordDeclaration(t *testing.T){
 path:=filepath.Join(os.Getenv("DECLARATION_COUNTER"),strings.ReplaceAll(t.Name(),"/","_"))
 f,err:=os.OpenFile(path,os.O_CREATE|os.O_APPEND|os.O_WRONLY,0600);if err!=nil{t.Fatal(err)}
 _,err=f.WriteString("x");f.Close();if err!=nil{t.Fatal(err)}
}
func(s *Override) TestCritical(){recordDeclaration(s.T());s.T().Error("ordinary override")}
func(s *Ordinary) TestCritical(){recordDeclaration(s.T());s.T().Error("ordinary independent declaration")}
func(s *Ordinary) TestValue(){recordDeclaration(s.T())}
func TestLocalPointer(t *testing.T){suite.Run(t,new(LocalPointer))}
func TestDerived(t *testing.T){suite.Run(t,new(Derived))}
func TestOverride(t *testing.T){suite.Run(t,new(Override))}
func TestOrdinaryDeclaration(t *testing.T){suite.Run(t,new(Ordinary))}
func TestHiddenDeclaration(t *testing.T){suite.Run(t,testkit.NewHidden())}
`})
	bin := filepath.Join(t.TempDir(), executableName("declarations.test"))
	out, stderr, code := command(t, dir, testEnv("DD_CIVISIBILITY_ENABLED=false"), driver, exclusionBuildArgs(bin, true)...)
	if code != 0 {
		t.Fatalf("compile %d: %s %s", code, out, stderr)
	}
	// Declaration registrations must stay in the consuming binary, including an
	// imported package which supplies no tests and whose source is now absent.
	if err := os.Rename(filepath.Join(helper, "base.go"), filepath.Join(helper, "base.go.saved")); err != nil {
		t.Fatal(err)
	}
	for _, mode := range []string{"in_process", "process"} {
		t.Run(mode, func(t *testing.T) {
			counters := t.TempDir()
			receiver, got := runParityCase(t, dir, bin, parityCase{Args: []string{"-test.run=^Test(Derived|Override|OrdinaryDeclaration|HiddenDeclaration|LocalPointer)$"}, Policy: policySettings{Retry: true, Quarantined: true, ManagementTarget: "TestDerived/TestCritical", ManagementSuite: "<autogenerated>/Derived"}, Env: []string{"DECLARATION_COUNTER=" + counters, "DD_CIVISIBILITY_FLAKY_RETRY_ENABLED=true", "DD_CIVISIBILITY_FLAKY_RETRY_COUNT=2", "DD_CIVISIBILITY_RETRY_EXECUTION_MODE=" + mode}})
			if got.code != 1 {
				t.Fatalf("exit %d: %s %s", got.code, got.out, got.stderr)
			}
			counts := map[string]string{
				"TestDerived/TestCritical": "x", "TestDerived/TestValue": "x",
				"TestHiddenDeclaration/TestHidden":  "x",
				"TestLocalPointer/TestLocalPointer": "x",
				"TestOverride/TestCritical":         "xxx", "TestOverride/TestValue": "x",
				"TestOrdinaryDeclaration/TestCritical": "xxx", "TestOrdinaryDeclaration/TestValue": "xxx",
			}
			for name, want := range counts {
				data, err := os.ReadFile(filepath.Join(counters, strings.ReplaceAll(name, "/", "_")))
				if err != nil || string(data) != want {
					t.Fatalf("%s calls=%q want=%q err=%v", name, data, want, err)
				}
			}
			protected, value, hidden := 0, 0, 0
			for _, event := range receiver.events {
				if event["type"] != "test" {
					continue
				}
				meta := event["content"].(map[string]any)["meta"].(map[string]any)
				name, _ := meta["test.name"].(string)
				if name == "TestDerived/TestCritical" {
					protected++
					for _, key := range []string{"prevent_failure_suppression", "no_auto_retry", "is_quarantined"} {
						if meta["test.test_management."+key] != "true" {
							t.Fatalf("imported promoted declaration lost %s: %v", key, meta)
						}
					}
				} else if name == "TestHiddenDeclaration/TestHidden" || name == "TestLocalPointer/TestLocalPointer" {
					hidden++
					if meta["test.test_management.no_auto_retry"] != "true" {
						t.Fatalf("unexported imported receiver lost declaration: %v", meta)
					}
				} else if name == "TestDerived/TestValue" || name == "TestOverride/TestValue" {
					value++
					if meta["test.test_management.no_auto_retry"] != "true" {
						t.Fatalf("value receiver declaration lost: %v", meta)
					}
					if meta["test.test_management.prevent_failure_suppression"] != nil {
						t.Fatalf("independent method inherited sibling annotation: %v", meta)
					}
				} else if strings.HasPrefix(name, "TestOverride/") || strings.HasPrefix(name, "TestOrdinaryDeclaration/") {
					for _, key := range []string{"prevent_failure_suppression", "no_auto_retry"} {
						if meta["test.test_management."+key] != nil {
							t.Fatalf("override or unrelated declaration leaked %s: %v", key, meta)
						}
					}
				}
			}
			if protected != 1 || value != 2 || hidden != 2 {
				t.Fatalf("protected events=%d value events=%d hidden events=%d", protected, value, hidden)
			}
		})
	}
}

// Cgo's compiler-selected Go sources participate in the same declaration scan
// as ordinary files, for both the local package and an imported suite helper.
func checkMiniCgoImportedExclusions(t *testing.T) {
	dir, driver := prepareMiniFixture(t)
	out, stderr, code := command(t, dir, testEnv(), "go", "env", "CGO_ENABLED")
	if code != 0 {
		t.Fatalf("native cgo configuration: %s %s", out, stderr)
	}
	if strings.TrimSpace(out) != "1" {
		t.Skip("native toolchain disables cgo")
	}
	helper := installExternalTestifyHelper(t, dir)
	writeBuildFixture(t, helper, map[string]string{"cgo.go": `package testkit
import "C"
import("os";"path/filepath";"strings";"github.com/stretchr/testify/suite")
type CgoBase struct{suite.Suite}
type CgoAlias = CgoBase
//ddtest:no_auto_retry
func(s *CgoAlias) TestCgo(){
 path:=filepath.Join(os.Getenv("DECLARATION_COUNTER"),strings.ReplaceAll(s.T().Name(),"/","_"))
 f,err:=os.OpenFile(path,os.O_CREATE|os.O_APPEND|os.O_WRONLY,0600);if err!=nil{s.T().Fatal(err)}
 _,err=f.WriteString("x");f.Close();if err!=nil{s.T().Fatal(err)}
 s.T().Error("imported cgo annotation")
}
`})
	writeBuildFixture(t, dir, map[string]string{"cgo.go": `package fixture
import "C"
import("os";"path/filepath";"strings";"github.com/stretchr/testify/suite")
type LocalCgo struct{suite.Suite}
type LocalAlias = LocalCgo
//ddtest:no_auto_retry
func(s *LocalAlias) TestCgo(){
 path:=filepath.Join(os.Getenv("DECLARATION_COUNTER"),strings.ReplaceAll(s.T().Name(),"/","_"))
 f,err:=os.OpenFile(path,os.O_CREATE|os.O_APPEND|os.O_WRONLY,0600);if err!=nil{s.T().Fatal(err)}
 _,err=f.WriteString("x");f.Close();if err!=nil{s.T().Fatal(err)}
 s.T().Error("local cgo annotation")
}
`, "cgo_test.go": `package fixture
import("testing";"example.com/external-testkit";"github.com/stretchr/testify/suite")
func TestImportedCgo(t *testing.T){suite.Run(t,new(testkit.CgoBase))}
func TestLocalCgo(t *testing.T){suite.Run(t,new(LocalCgo))}
`})
	bin := filepath.Join(t.TempDir(), executableName("cgo-declarations.test"))
	out, stderr, code = command(t, dir, testEnv("DD_CIVISIBILITY_ENABLED=false"), driver, exclusionBuildArgs(bin, true)...)
	if code != 0 {
		t.Fatalf("compile native cgo fixture %d: %s %s", code, out, stderr)
	}
	for _, mode := range []string{"in_process", "process"} {
		t.Run(mode, func(t *testing.T) {
			counters := t.TempDir()
			receiver, got := runParityCase(t, dir, bin, parityCase{Args: []string{"-test.run=^Test(Imported|Local)Cgo$"}, Policy: policySettings{Retry: true}, Env: []string{"DECLARATION_COUNTER=" + counters, "DD_CIVISIBILITY_FLAKY_RETRY_ENABLED=true", "DD_CIVISIBILITY_FLAKY_RETRY_COUNT=2", "DD_CIVISIBILITY_RETRY_EXECUTION_MODE=" + mode}})
			if got.code != 1 {
				t.Fatalf("exit %d: %s %s", got.code, got.out, got.stderr)
			}
			for _, name := range []string{"TestImportedCgo/TestCgo", "TestLocalCgo/TestCgo"} {
				data, err := os.ReadFile(filepath.Join(counters, strings.ReplaceAll(name, "/", "_")))
				if err != nil || string(data) != "x" {
					t.Fatalf("%s calls=%q want=x err=%v", name, data, err)
				}
				count := 0
				for _, event := range receiver.events {
					if event["type"] != "test" {
						continue
					}
					meta := event["content"].(map[string]any)["meta"].(map[string]any)
					if meta["test.name"] != name {
						continue
					}
					count++
					if meta["test.test_management.no_auto_retry"] != "true" || meta["test.is_retry"] != nil || meta["test.retry_reason"] != nil {
						t.Fatalf("cgo declaration tags: %v", meta)
					}
				}
				if count != 1 {
					t.Fatalf("%s emitted %d events, want one", name, count)
				}
			}
		})
	}
}

// A runtime dependency's internal test package cannot import testopt: doing so
// would create a cycle through the dependency under test. Its bootstrap and
// declaration registrations must both live in the external test package.
func checkMiniRuntimeDependencyExclusions(t *testing.T) {
	_, driver := prepareMiniFixture(t)
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	sources := t.TempDir()
	writeBuildFixture(t, sources, map[string]string{"annotation_test.go": `package minitracer
import("os";"testing")
//ddtest:no_auto_retry
func TestAnnotatedRuntimeDependency(t *testing.T){
 f,err:=os.OpenFile(os.Getenv("DECLARATION_COUNTER"),os.O_CREATE|os.O_APPEND|os.O_WRONLY,0600);if err!=nil{t.Fatal(err)}
 _,err=f.WriteString("x");f.Close();if err!=nil{t.Fatal(err)}
 t.Error("annotated internal runtime-dependency test")
}
`})
	encoded, err := json.Marshal(map[string]any{"Replace": map[string]string{filepath.Join(root, "internal", "minitracer", "annotation_test.go"): filepath.Join(sources, "annotation_test.go")}})
	if err != nil {
		t.Fatal(err)
	}
	overlay := filepath.Join(sources, "overlay.json")
	if err := os.WriteFile(overlay, encoded, 0600); err != nil {
		t.Fatal(err)
	}
	bin := filepath.Join(t.TempDir(), executableName("runtime-dependency.test"))
	args := exclusionBuildArgs(bin, true)
	args = append(args[:len(args)-1], "-overlay="+overlay, "./internal/minitracer")
	out, stderr, code := command(t, root, testEnv("DD_CIVISIBILITY_ENABLED=false"), driver, args...)
	if code != 0 {
		t.Fatalf("compile runtime-dependency internal annotation %d: %s %s", code, out, stderr)
	}
	for _, mode := range []string{"in_process", "process"} {
		t.Run(mode, func(t *testing.T) {
			counter := filepath.Join(t.TempDir(), "calls")
			receiver, got := runParityCase(t, root, bin, parityCase{Args: []string{"-test.run=^TestAnnotatedRuntimeDependency$"}, Policy: policySettings{Retry: true}, Env: []string{"DECLARATION_COUNTER=" + counter, "DD_CIVISIBILITY_FLAKY_RETRY_ENABLED=true", "DD_CIVISIBILITY_FLAKY_RETRY_COUNT=2", "DD_CIVISIBILITY_RETRY_EXECUTION_MODE=" + mode}})
			if got.code != 1 {
				t.Fatalf("exit %d: %s %s", got.code, got.out, got.stderr)
			}
			data, err := os.ReadFile(counter)
			if err != nil || string(data) != "x" {
				t.Fatalf("calls=%q err=%v", data, err)
			}
			count := 0
			for _, event := range receiver.events {
				if event["type"] != "test" {
					continue
				}
				meta := event["content"].(map[string]any)["meta"].(map[string]any)
				if meta["test.name"] != "TestAnnotatedRuntimeDependency" {
					continue
				}
				count++
				if meta["test.test_management.no_auto_retry"] != "true" {
					t.Fatalf("runtime-dependency declaration lost: %v", meta)
				}
			}
			if count != 1 {
				t.Fatalf("events=%d want=1", count)
			}
		})
	}
}

func checkMiniGenericDeclarations(t *testing.T) {
	dir, driver := prepareMiniFixture(t)
	helper := installExternalTestifyHelper(t, dir)
	writeBuildFixture(t, helper, map[string]string{"generic.go": `package testkit
import("os";"path/filepath";"strings";"testing";"github.com/stretchr/testify/suite")
type hiddenGeneric[T any] struct{suite.Suite}
func genericRecord(t *testing.T){
 path:=filepath.Join(os.Getenv("DECLARATION_COUNTER"),strings.ReplaceAll(t.Name(),"/","_"))
 f,err:=os.OpenFile(path,os.O_CREATE|os.O_APPEND|os.O_WRONLY,0600);if err!=nil{t.Fatal(err)}
 _,err=f.WriteString("x");f.Close();if err!=nil{t.Fatal(err)}
}
//ddtest:prevent_failure_suppression
//ddtest:no_auto_retry
func(s (*hiddenGeneric[T])) TestCritical(){genericRecord(s.T());s.T().Error("imported generic critical")}
//ddtest:no_auto_retry
func(s (hiddenGeneric[T])) TestValue(){genericRecord(s.T())}
func(s *hiddenGeneric[T]) TestOrdinary(){genericRecord(s.T())}
func NewGeneric[T any]() suite.TestingSuite{return new(hiddenGeneric[T])}
`})
	writeBuildFixture(t, dir, map[string]string{"generic_test.go": `package fixture_test
import("os";"path/filepath";"strings";"testing";"example.com/external-testkit";"github.com/stretchr/testify/suite")
type LocalGeneric[A,B any] struct{suite.Suite}
type UnrelatedGeneric[T any] struct{suite.Suite}
func(s *UnrelatedGeneric[T]) TestCritical(){recordGeneric(s.T());s.T().Error("ordinary unrelated generic")}
func(s UnrelatedGeneric[T]) TestValue(){recordGeneric(s.T())}

func recordGeneric(t *testing.T){
 path:=filepath.Join(os.Getenv("DECLARATION_COUNTER"),strings.ReplaceAll(t.Name(),"/","_"))
 f,err:=os.OpenFile(path,os.O_CREATE|os.O_APPEND|os.O_WRONLY,0600);if err!=nil{t.Fatal(err)}
 _,err=f.WriteString("x");f.Close();if err!=nil{t.Fatal(err)}
}
//ddtest:prevent_failure_suppression
//ddtest:no_auto_retry
func(s (*LocalGeneric[A,B])) TestCritical(){recordGeneric(s.T());s.T().Error("local generic critical")}
//ddtest:no_auto_retry
func(s (LocalGeneric[A,B])) TestValue(){recordGeneric(s.T())}
func(s *LocalGeneric[A,B]) TestOrdinary(){recordGeneric(s.T())}
func TestUnrelatedGenericInt(t *testing.T){recordGeneric(t);suite.Run(t,new(UnrelatedGeneric[int]))}
func TestLocalGenericInt(t *testing.T){recordGeneric(t);suite.Run(t,new(LocalGeneric[int,string]))}
func TestLocalGenericString(t *testing.T){recordGeneric(t);suite.Run(t,new(LocalGeneric[string,int]))}
func TestImportedGenericInt(t *testing.T){recordGeneric(t);suite.Run(t,testkit.NewGeneric[int]())}
func TestImportedGenericString(t *testing.T){recordGeneric(t);suite.Run(t,testkit.NewGeneric[string]())}
`})
	bin := filepath.Join(t.TempDir(), executableName("generic-declarations.test"))
	out, stderr, code := command(t, dir, testEnv("DD_CIVISIBILITY_ENABLED=false"), driver, exclusionBuildArgs(bin, true)...)
	if code != 0 {
		t.Fatalf("compile generic receivers %d: %s %s", code, out, stderr)
	}
	for _, mode := range []string{"in_process", "process"} {
		t.Run(mode, func(t *testing.T) {
			counters := t.TempDir()
			receiver, got := runParityCase(t, dir, bin, parityCase{Args: []string{"-test.run=^Test(Local|Imported|Unrelated)Generic(Int|String)$"}, Policy: policySettings{Retry: true}, Env: []string{"DECLARATION_COUNTER=" + counters, "DD_CIVISIBILITY_RETRY_EXECUTION_MODE=" + mode, "DD_CIVISIBILITY_FLAKY_RETRY_ENABLED=true", "DD_CIVISIBILITY_FLAKY_RETRY_COUNT=2"}})
			if got.code != 1 {
				t.Fatalf("exit %d: %s %s", got.code, got.out, got.stderr)
			}
			// An unrelated generic receiver with identical method names keeps
			// ordinary retry behavior and receives no declaration flags.
			for _, suffix := range []string{"", "/TestCritical", "/TestValue"} {
				name := "TestUnrelatedGenericInt" + suffix
				data, err := os.ReadFile(filepath.Join(counters, strings.ReplaceAll(name, "/", "_")))
				if err != nil || string(data) != "xxx" {
					t.Fatalf("%s callbacks=%q want=xxx err=%v", name, data, err)
				}
			}
			unrelatedEvents := 0
			for _, event := range receiver.events {
				if event["type"] != "test" {
					continue
				}
				meta := event["content"].(map[string]any)["meta"].(map[string]any)
				name, _ := meta["test.name"].(string)
				if !strings.HasPrefix(name, "TestUnrelatedGenericInt/") {
					continue
				}
				unrelatedEvents++
				if meta["test.test_management.no_auto_retry"] != nil || meta["test.test_management.prevent_failure_suppression"] != nil {
					t.Fatalf("unrelated generic inherited annotation: %v", meta)
				}
			}
			// Ordinary process-worker subtest spans retain the existing replay
			// scope: callback counters above prove retries even when only the
			// initial ordinary event is emitted. Excluded spans stay exact below.
			ordinaryEvents := 3
			if mode == "process" {
				ordinaryEvents = 1
			}
			if unrelatedEvents != 2*ordinaryEvents {
				t.Fatalf("unrelated generic events=%d want=%d", unrelatedEvents, 2*ordinaryEvents)
			}
			for _, root := range []string{"TestLocalGenericInt", "TestLocalGenericString", "TestImportedGenericInt", "TestImportedGenericString"} {
				for suffix, want := range map[string]string{"": "xxx", "/TestCritical": "x", "/TestValue": "x", "/TestOrdinary": "xxx"} {
					name := root + suffix
					data, err := os.ReadFile(filepath.Join(counters, strings.ReplaceAll(name, "/", "_")))
					if err != nil || string(data) != want {
						t.Fatalf("%s callbacks=%q want=%q err=%v", name, data, want, err)
					}
				}
				counts := map[string]int{}
				for _, event := range receiver.events {
					if event["type"] != "test" {
						continue
					}
					meta := event["content"].(map[string]any)["meta"].(map[string]any)
					name, _ := meta["test.name"].(string)
					if !strings.HasPrefix(name, root+"/") {
						continue
					}
					method := strings.TrimPrefix(name, root+"/")
					counts[method]++
					critical := method == "TestCritical"
					excluded := critical || method == "TestValue"
					if excluded {
						if meta["test.test_management.no_auto_retry"] != "true" {
							t.Fatalf("generic annotation lost: %v", meta)
						}
						for _, key := range []string{"test.is_retry", "test.retry_reason", "test.retry.execution_mode"} {
							if meta[key] != nil {
								t.Fatalf("generic excluded test retried: %v", meta)
							}
						}
					} else if meta["test.test_management.no_auto_retry"] != nil {
						t.Fatalf("generic sibling inherited exclusion: %v", meta)
					}
					if critical {
						if meta["test.test_management.prevent_failure_suppression"] != "true" || meta["test.status"] != "fail" {
							t.Fatalf("generic critical policy lost: %v", meta)
						}
					} else if meta["test.test_management.prevent_failure_suppression"] != nil {
						t.Fatalf("generic sibling inherited critical policy: %v", meta)
					}
				}
				if counts["TestCritical"] != 1 || counts["TestValue"] != 1 || counts["TestOrdinary"] != ordinaryEvents {
					t.Fatalf("%s event counts=%v", root, counts)
				}
			}
		})
	}
}
