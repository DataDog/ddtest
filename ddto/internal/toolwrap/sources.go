package toolwrap

import (
	"crypto/sha256"
	"embed"
	"encoding/hex"
	"io/fs"
	"slices"
	"strconv"
)

// The package's own sources, which the wrapper executable compiles.
//
//go:embed toolwrap.go exec_unix.go exec_windows.go
var sources embed.FS

// Executable is the wrapper executable's name, without the platform's suffix.
const Executable = "ddto-toolwrap"

// wrapperModule is the module path of the wrapper executable's sources.
const wrapperModule = "ddtotoolwrap"

// Sources returns the wrapper executable's module, by file name, and its key:
// a digest of every file that ddto would build. prefix starts ddto's error
// messages and is part of the key, as is the version that it names.
func Sources(prefix string) (files map[string][]byte, key string) {
	files = map[string][]byte{
		// The oldest language version that ddto supports.
		"go.mod": []byte("module " + wrapperModule + "\n\ngo 1.25\n"),
	}
	entries, err := fs.ReadDir(sources, ".")
	if err != nil {
		panic(err)
	}
	for _, entry := range entries {
		data, err := fs.ReadFile(sources, entry.Name())
		if err != nil {
			panic(err)
		}
		files["toolwrap/"+entry.Name()] = data
	}
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	slices.Sort(names)
	digest := sha256.New()
	for _, name := range names {
		digest.Write([]byte(name + "\x00" + strconv.Itoa(len(files[name])) + "\x00"))
		digest.Write(files[name])
	}
	digest.Write([]byte(mainSource + "\x00" + prefix))
	key = hex.EncodeToString(digest.Sum(nil))
	files["main.go"] = []byte(mainSource + "\nconst (\n\tkey    = " + strconv.Quote(key) + "\n\tprefix = " + strconv.Quote(prefix) + "\n)\n")
	return files, key
}

const mainSource = `// Code generated by ddto. DO NOT EDIT.

// Command ddto-toolwrap runs go's tool invocations for ddto's -toolexec.
package main

import (
	"os"

	"` + wrapperModule + `/toolwrap"
)

func main() {
	os.Exit(toolwrap.Main(os.Args[1:], key, prefix))
}
`
